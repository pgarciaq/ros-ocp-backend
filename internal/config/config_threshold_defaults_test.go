	assert.True(t, cfg.EnableVMRecs)
	assert.InDelta(t, 0.95, cfg.VMCPUPercentileCost, 1e-9)
	assert.InDelta(t, 0.99, cfg.VMCPUPercentilePerf, 1e-9)
