	ResetForTest()
	cfg := GetConfig()

	assert.InDelta(t, 0.60, cfg.ContainerCPUCostPercentile, 1e-9)
	assert.InDelta(t, 0.98, cfg.ContainerCPUPerfPercentile, 1e-9)
